def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_AGENT_RESPONSE_COMPLIANCE = frozenset({'no_policy_applies', 'non_compliant', 'partial', 'compliant'})
    _v = str(record.get("agent_response_compliance", "")).strip().lower()
    if _v not in _VALID_AGENT_RESPONSE_COMPLIANCE:
        logger.warning(
            "uid=%s: invalid agent_response_compliance %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_AGENT_RESPONSE_COMPLIANCE)
        )
        record["agent_response_compliance"] = ""
    else:
        record["agent_response_compliance"] = _v
    _VALID_POLICY_TOO_STRICT = frozenset({'yes', 'not_applicable', 'no'})
    _v = str(record.get("policy_too_strict", "")).strip().lower()
    if _v not in _VALID_POLICY_TOO_STRICT:
        logger.warning(
            "uid=%s: invalid policy_too_strict %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_POLICY_TOO_STRICT)
        )
        record["policy_too_strict"] = ""
    else:
        record["policy_too_strict"] = _v
    _VALID_POLICY_GAP = frozenset({'yes', 'not_applicable', 'no'})
    _v = str(record.get("policy_gap", "")).strip().lower()
    if _v not in _VALID_POLICY_GAP:
        logger.warning(
            "uid=%s: invalid policy_gap %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_POLICY_GAP)
        )
        record["policy_gap"] = ""
    else:
        record["policy_gap"] = _v
    return record


async def classify_policy_compliance(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run policy_compliance classification on all batches."""
    tax = taxonomies.get("policy_compliance", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "PC")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("policy_compliance: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_policy_compliance(batches, taxonomies, cfg))
