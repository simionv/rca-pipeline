def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_POLICY_UNDERSTANDING_ISSUE = frozenset({'no', 'yes'})
    _v = str(record.get("policy_understanding_issue", "")).strip().lower()
    if _v not in _VALID_POLICY_UNDERSTANDING_ISSUE:
        logger.warning(
            "uid=%s: invalid policy_understanding_issue %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_POLICY_UNDERSTANDING_ISSUE)
        )
        record["policy_understanding_issue"] = ""
    else:
        record["policy_understanding_issue"] = _v
    _VALID_CONFIDENCE = frozenset({'low', 'medium', 'high'})
    _v = str(record.get("confidence", "")).strip().lower()
    if _v not in _VALID_CONFIDENCE:
        logger.warning(
            "uid=%s: invalid confidence %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_CONFIDENCE)
        )
        record["confidence"] = ""
    else:
        record["confidence"] = _v
    return record


