async def classify_policy_rules(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run policy_rules classification on all batches."""
    tax = taxonomies.get("policy_rules", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "PA")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        
    )

    logger.info("policy_rules: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_policy_rules(batches, taxonomies, cfg))
