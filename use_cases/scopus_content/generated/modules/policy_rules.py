def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: You are an expert classifier for Elsevier support tickets. Your task: identify which SPECIFIC Scopus content policy rules (not just broad policy areas) applied to this ticket, and whether the agent's handling complied with each one individually. Each leaf code in the taxonomy below (e.g. PA5.1, PA10.2) is one atomic, checkable rule drawn from the Scopus Content Coverage Guide and CAR Creation Manual. A ticket may touch multiple rules across one or more policy areas, or none at all. Use the taxonomy below to make your assessment.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Review the ticket against the numbered policy rules in the taxonomy below (each leaf code like PA5.1 or PA10.2 is one specific, atomic rule). For every rule that is genuinely relevant to this ticket's topic -- i.e. the rule's subject matter was raised, or should have governed the agent's response -- return one object with: 'code' (the exact leaf code), 'verdict' (one of: compliant, non_compliant, partial, not_applicable), and 'evidence' (a single verbatim quote copied EXACTLY, character-for-character, from the customer/agent conversation text -- NEVER the rule description itself, a paraphrase, or a summary. If you cannot find such an exact quote in the conversation, return an empty string for evidence -- do not describe the rule instead). compliant = the agent's handling matched this specific rule. non_compliant = the agent's handling directly contradicted or ignored this specific rule. partial = broadly correct but missed or misstated a detail of this specific rule. not_applicable = the rule's topic was raised but this particular rule doesn't govern the outcome (rare -- prefer omitting the rule entirely over tagging it not_applicable). If no rules in the taxonomy are relevant to this ticket at all, return an empty list []. Only return rules that are genuinely relevant -- do not return every rule in the taxonomy for every ticket. Do not tag a rule just because the ticket's general topic is nearby (e.g. any metadata-correction ticket is NOT automatically every PA18 criterion) -- only tag a rule if the conversation specifically discusses, triggers, or should have triggered that exact rule. Most tickets will match 0-2 rules; a ticket matching many rules from the same area is a red flag -- double-check each one individually rather than tagging the whole area at once. When in doubt, leave the rule out. Do NOT reuse the identical evidence quote across multiple different rule codes -- if the same quote would 'support' every sub-criterion in an area, that is a sign you should tag only the ONE rule that quote most specifically and distinctly supports, not all of them. Before tagging any PA18 (missing content) criterion, confirm the ticket is genuinely about content that has never been indexed and is reported missing -- a request to correct or fix data on content that IS already indexed is PA16 (errata/corrections), not PA18, even if the customer also mentions the item is 'missing' from their profile view. → `matched_rules`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "matched_rules": [{"code": "<code>", "verdict": "<verdict>", "evidence": "<evidence>"}]
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


