def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Classify each ScienceDirect support ticket into exactly one of two primary classifications: Accessing content or Anything else. Analyse each ScienceDirect ticket using the full conversation thread. Classify based on the customer’s actual need. Agent messages can confirm context, but do not infer information that is not explicit in the ticket. Assign the single best-fitting LEAF code (e.g. SDAP1.1). Decide on what the customer actually needs, not on the vocabulary they use. The word access on its own is never enough. Apply these tests in order. First, if what blocks the customer is a credential or a sign-in - a password, a login, ID+, account activation, account switching, or SSO - the answer is Anything else, even when a specific article is named. Second, if what blocks them is the machine or the network - cache, cookies, a browser, a device, a VPN or a proxy - or an explicit block such as an IP restriction, a Content Protection block, a security control or a high-download block, the answer is Anything else. Third, if the request is administrative or commercial - a profile change, billing, an invoice, a refund, a cancellation - or concerns ScienceDirect AI, the answer is Anything else. Only when none of those apply, ask whether the customer is trying to obtain, read, download or receive specific content, to confirm whether they or their institution can reach specific content, to resolve a failure to reach content they expect to be entitled to, or to reach content they bought themselves. If so, the answer is Accessing content. If the ticket does not say enough to place it either way, answer Anything else rather than assuming a content request.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Assign the single leaf-level code (e.g. SDAP1.1) for the primary classification that best matches this ticket. Read each Definition in full and match on what the ticket shows, not on surface keywords. Only use codes from the taxonomy. → `sdap_code`
2. In one or two sentences, explain why this primary classification applies and why the other classification does not. Refer to what the ticket actually shows. Do not use apostrophes or quotation marks in your answer. → `sdap_justification`
3. Copy verbatim the single sentence or phrase from the transcript that most strongly supports this choice. Do not paraphrase, infer, or add words that are not in the transcript. If no direct evidence exists, return an empty string. → `sdap_evidence`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "sdap_code": "<SDAP_code>",
    "sdap_justification": "<string>",
    "sdap_evidence": "<string>"
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


