async def classify_s2ls_escalation_effort(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run s2ls_escalation_effort classification on all batches."""
    tax = taxonomies.get("s2ls_escalation_effort", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "SLJ")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("s2ls_escalation_effort: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
