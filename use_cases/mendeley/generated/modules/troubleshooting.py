from __future__ import annotations

import asyncio
import logging
from typing import Any

from rca_pipeline.config import RunConfig
from rca_pipeline.taxonomy import taxonomy_to_rich_prompt
from rca_pipeline.llm_client import process_batches_async

logger = logging.getLogger(__name__)

MODULE_NAME = "troubleshooting"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Identifies troubleshooting steps taken by the agent during the interaction.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. List all TS codes for steps taken in the order they appear in the transcript. → `troubleshooting_step_codes`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "troubleshooting_step_codes": ["<item1>", "<item2>"]
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, troubleshooting_step_codes"""





async def classify_troubleshooting(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run troubleshooting classification on all batches."""
    tax = taxonomies.get("troubleshooting_steps", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "TS")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        
    )

    logger.info("troubleshooting: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_troubleshooting(batches, taxonomies, cfg))
