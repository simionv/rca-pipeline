from __future__ import annotations

import asyncio
import logging
from typing import Any

from rca_pipeline.config import RunConfig
from rca_pipeline.taxonomy import taxonomy_to_rich_prompt
from rca_pipeline.llm_client import process_batches_async

logger = logging.getLogger(__name__)

MODULE_NAME = "resolution"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Classifies how the interaction was resolved.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Determine resolution status: resolved/workaround/escalated/pending/no_action. → `resolution_status`
2. Assign the most specific resolution taxonomy code. → `resolution_code`
3. Write a short concrete case-specific description of what was done (max 15 words). → `resolution_description`
4. Copy-paste the single most relevant sentence VERBATIM from the transcript. Use the customer's or agent's exact words — do not paraphrase, summarise, infer, or add any words not present in the transcript. If you cannot find a direct quote that supports your classification, return an empty string "". → `resolution_status_evidence`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "resolution_status": "<resolved | workaround | escalated | pending | no_action>",
    "resolution_code": "<RS_code>",
    "resolution_description": "<string>",
    "resolution_status_evidence": "<string>"
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, resolution_status, resolution_code, resolution_description, resolution_status_evidence"""


def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_RESOLUTION_STATUS = frozenset({'resolved', 'no_action', 'escalated', 'workaround', 'pending'})
    _v = str(record.get("resolution_status", "")).strip().lower()
    if _v not in _VALID_RESOLUTION_STATUS:
        logger.warning(
            "uid=%s: invalid resolution_status %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_RESOLUTION_STATUS)
        )
        record["resolution_status"] = ""
    else:
        record["resolution_status"] = _v
    return record


async def classify_resolution(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run resolution classification on all batches."""
    tax = taxonomies.get("resolution_codes", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "RS")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("resolution: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_resolution(batches, taxonomies, cfg))
