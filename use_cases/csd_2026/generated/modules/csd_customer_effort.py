def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_EFFORT_SCORE = frozenset({'very_low', 'high', 'very_high', 'low', 'medium'})
    _v = str(record.get("effort_score", "")).strip().lower()
    if _v not in _VALID_EFFORT_SCORE:
        logger.warning(
            "uid=%s: invalid effort_score %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_EFFORT_SCORE)
        )
        record["effort_score"] = ""
    else:
        record["effort_score"] = _v
    _VALID_RESOLUTION_TRANSPARENCY = frozenset({'na', 'opaque', 'partial', 'transparent'})
    _v = str(record.get("resolution_transparency", "")).strip().lower()
    if _v not in _VALID_RESOLUTION_TRANSPARENCY:
        logger.warning(
            "uid=%s: invalid resolution_transparency %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_RESOLUTION_TRANSPARENCY)
        )
        record["resolution_transparency"] = ""
    else:
        record["resolution_transparency"] = _v
    return record


