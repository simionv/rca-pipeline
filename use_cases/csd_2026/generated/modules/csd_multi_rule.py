def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: List EVERY Scopus content validation rule that this rejected support request violates. There are 24 numbered rules from the CSD triangulation matrix, plus CSDVR4.1 for 'no rule applies'. This is deliberately a MULTI-LABEL task: a ticket may violate one rule or several, and which is more common is not known in advance - establishing that is the whole point of this pass, so do not assume either way. Judge each rule independently on its own condition, as a separate yes/no decision. The question is which rules APPLY, not which applies best, so never drop a rule merely because another one fits the ticket better. A rule applies only when the transcript contains explicit evidence for its condition; a standing disclaimer, a generic timeline sentence, or a possibility raised and then dismissed is not evidence. If no rule applies, return CSDVR4.1 alone.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. REQUIRED. Return a JSON list of every validation rule leaf code that applies to this ticket, for example ["CSDVR1.5"] or ["CSDVR1.5", "CSDVR1.7"]. Use leaf codes exactly as they appear in the taxonomy. Work through the rules and include every one whose own condition is explicitly evidenced in the transcript, and only those. Do not add a rule that lacks its own evidence, and do not leave out a rule that has it. If nothing applies, return ["CSDVR4.1"] on its own and never combine CSDVR4.1 with another code. → `mr_codes`
2. Of the rules you listed in mr_codes, give the single leaf code that fits best. It must be one of the codes you listed. This is used to check this pass against the original single-label run, so answer it independently of what any earlier classification might have said. → `mr_primary`
3. If mr_codes contains more than one rule, quote verbatim from the transcript the sentence that satisfies the SECOND rule - not the first. This is the evidence that the ticket really does break more than one rule, so it must be a direct quote and must be about a different condition from the primary rule. If only one rule applies, return an empty string. → `mr_secondary_evidence`
4. In at most 40 words, say why each listed rule applies. Where you listed only one rule, say briefly which rule was the closest runner-up and what evidence it lacked. → `mr_justification`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "mr_codes": ["<item1>", "<item2>"],
    "mr_primary": "<CSDVR_code>",
    "mr_secondary_evidence": "<string>",
    "mr_justification": "<string>"
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, mr_codes, mr_primary, mr_secondary_evidence, mr_justification"""





async def classify_csd_multi_rule(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run csd_multi_rule classification on all batches."""
    tax = taxonomies.get("csd_validation_rule", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "CSDVR")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        
    )

    logger.info("csd_multi_rule: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_csd_multi_rule(batches, taxonomies, cfg))
