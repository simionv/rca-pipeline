def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Classify the specific action(s) the agent took to resolve the customer's issue. This captures WHAT was done (refund issued, workaround provided, ticket raised) rather than HOW WELL it was done - that is assessed by the resolution_quality module. Assign the most significant action as primary; list secondary actions separately.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Select the single most significant action taken by the agent to address the customer's issue. Focus on what was DONE, not how well it was done. If the agent provided information AND applied a credit, choose the more impactful action as primary. → `resolution_action_primary_code`
2. Describe in one sentence (max 30 words) the concrete action taken. Be specific: prefer 'issued a £12.50 partial refund for the duplicate charge' over 'processed refund'. If no action was taken, describe why. → `resolution_action_description`
3. List up to 3 additional resolution action codes taken in this interaction (e.g. ['RA2.3', 'RA4.1']). Return [] if only one action was taken. Do not repeat the primary code. → `secondary_resolution_actions`
4. Return true if the resolution was fully executed during this interaction (e.g. refund processed, settings changed, information provided and confirmed). Return false if the resolution requires a subsequent action or will complete after the interaction ends. → `resolution_immediate`
5. Extract the exact date, time, or timeframe the agent committed to for resolution completion (e.g. '3-5 business days', 'by Friday 23rd', 'within 24 hours'). Return 'not specified' if no timeline was committed, or 'immediate' if resolved during the call. → `committed_completion_date`
6. Return true if the action taken directly addressed the harm or inconvenience the customer reported (e.g. refund for an overcharge, fix for a broken feature, apology for rude service). Return false if the action was procedural but did not directly address the customer's stated impact. → `customer_impact_mitigated`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "resolution_action_primary_code": "<RA_code>",
    "resolution_action_description": "<string>",
    "secondary_resolution_actions": ["<item1>", "<item2>"],
    "resolution_immediate": true,
    "committed_completion_date": "<string>",
    "customer_impact_mitigated": true
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


