def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Identify compliance, legal, safety, fraud, or reputational risk signals present in the transcript. Flag any signal that warrants escalation to a compliance, legal, or safeguarding team. Assign 'No risk identified' if no signals are present - do not leave this field blank.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Select the single most serious risk signal present in the transcript. If no risk signals are present, assign the 'No risk identified' code - do not leave this blank. When multiple risk signals exist, prioritise: safety > fraud > legal > vulnerability > reputational. → `risk_primary_code`
2. critical - requires immediate escalation to compliance, legal, or safeguarding; high - significant risk requiring prompt action today; medium - notable risk, should be reviewed by a team lead or compliance team; low - minor signal, flag for awareness but no urgent action needed; none - no risk signals detected in this interaction. → `risk_severity`
3. Return true if the risk signal is serious enough to require action before the interaction closes or within the same business day: physical safety, suspected fraud, legal threat with solicitor named, severe vulnerability. Return false for lower severity signals. → `immediate_escalation_required`
4. Extract the specific transcript passage (max 50 words) that contains the risk signal. Verbatim quotes are strongly preferred. If no risk was found, return an empty string. → `risk_evidence`
5. List up to 3 additional risk codes present in the transcript. Return [] if only one risk signal exists or if no risks were identified. → `secondary_risk_signals`
6. Return true if ANY vulnerability signal is present: financial hardship, mental health mention, bereavement, elderly or disability indication, evident distress beyond normal frustration. Return false if no vulnerability signals are detected. → `vulnerability_flag`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "risk_primary_code": "<RISK_code>",
    "risk_severity": "<critical | high | medium | low | none>",
    "immediate_escalation_required": true,
    "risk_evidence": "<string>",
    "secondary_risk_signals": ["<item1>", "<item2>"],
    "vulnerability_flag": true
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, risk_primary_code, risk_severity, immediate_escalation_required, risk_evidence, secondary_risk_signals, vulnerability_flag"""


def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_RISK_SEVERITY = frozenset({'none', 'medium', 'high', 'critical', 'low'})
    _v = str(record.get("risk_severity", "")).strip().lower()
    if _v not in _VALID_RISK_SEVERITY:
        logger.warning(
            "uid=%s: invalid risk_severity %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_RISK_SEVERITY)
        )
        record["risk_severity"] = ""
    else:
        record["risk_severity"] = _v
    return record


async def classify_compliance_and_risk(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run compliance_and_risk classification on all batches."""
    tax = taxonomies.get("compliance_and_risk", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "RISK")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("compliance_and_risk: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_compliance_and_risk(batches, taxonomies, cfg))
