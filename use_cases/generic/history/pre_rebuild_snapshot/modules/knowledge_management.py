from rca_pipeline.config import RunConfig
from rca_pipeline.taxonomy import taxonomy_to_rich_prompt
from rca_pipeline.llm_client import process_batches_async

logger = logging.getLogger(__name__)

MODULE_NAME = "knowledge_management"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Identify whether this interaction reveals a gap in the company's documentation, knowledge base, or FAQ - and what type of knowledge asset would close that gap. Also flag internal knowledge or training gaps observed in the agent's responses. Assign 'No knowledge gap' if existing resources are adequate.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Select the most significant knowledge gap identified. If existing resources are adequate and the customer was successfully directed to them, assign 'No knowledge gap'. Do not leave this blank - a 'no gap' finding is valid data. → `knowledge_gap_primary_code`
2. create_new - a help article does not exist for this scenario and should be written; update_existing - an article exists but is inaccurate, incomplete, or outdated; improve_findability - the content exists but customers cannot find it (SEO, navigation, tagging); internal_only - an internal knowledge base or agent runbook update is needed (not customer-facing); none - no knowledge base action required. → `article_action_needed`
3. If a new or updated article is needed, suggest a concise, customer-friendly article title (max 10 words) that captures what the article should cover. Examples: 'How to recover access to a locked account', 'Why your citation count may differ between databases'. Return empty string if no article is needed. → `suggested_article_title`
4. Extract the transcript passage (max 40 words) that most clearly shows the gap: customer saying they could not find documentation, agent unable to answer, or customer having incorrect expectations from existing docs. Return empty string if no gap is identified. → `knowledge_gap_evidence`
5. Return true if the agent provided incorrect information, admitted they did not know, had to put the customer on hold to check basic product information, or gave an answer that contradicts known policy or product behaviour. Return false otherwise. → `agent_knowledge_gap`
6. If agent_knowledge_gap is true, describe in one short phrase (max 8 words) what the agent should be trained on. Examples: 'refund policy for annual subscriptions', 'API authentication error codes and resolution steps'. Return empty string if no agent knowledge gap was found. → `training_topic`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "knowledge_gap_primary_code": "<KM_code>",
    "article_action_needed": "<create_new | update_existing | improve_findability | internal_only | none>",
    "suggested_article_title": "<string>",
    "knowledge_gap_evidence": "<string>",
    "agent_knowledge_gap": true,
    "training_topic": "<string>"
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, knowledge_gap_primary_code, article_action_needed, suggested_article_title, knowledge_gap_evidence, agent_knowledge_gap, training_topic"""


def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_ARTICLE_ACTION_NEEDED = frozenset({'internal_only', 'none', 'improve_findability', 'create_new', 'update_existing'})
    _v = str(record.get("article_action_needed", "")).strip().lower()
    if _v not in _VALID_ARTICLE_ACTION_NEEDED:
        logger.warning(
            "uid=%s: invalid article_action_needed %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_ARTICLE_ACTION_NEEDED)
        )
        record["article_action_needed"] = ""
    else:
        record["article_action_needed"] = _v
    return record


async def classify_knowledge_management(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run knowledge_management classification on all batches."""
    tax = taxonomies.get("knowledge_management", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "KM")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("knowledge_management: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_knowledge_management(batches, taxonomies, cfg))
