logger = logging.getLogger(__name__)

MODULE_NAME = "root_cause"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Identifies the root cause of the support issue with justification and evidence from the transcript.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Identify the access domain (e.g. platform, subscription, content, API, billing). → `root_cause_access_domain`
2. Assign the most specific root cause taxonomy code. Focus on WHY the issue occurred, not what the symptom was. → `root_cause_primary_code`
3. Write a short concrete case-specific description (max 15 words). → `root_cause_primary_description`
4. Explain WHY this code fits, linking evidence to taxonomy definition (1-3 sentences). → `root_cause_justification`
5. Copy-paste the single most relevant sentence VERBATIM from the transcript. Use the customer's or agent's exact words — do not paraphrase, summarise, infer, or add any words not present in the transcript. If you cannot find a direct quote that supports your classification, return an empty string "". → `root_cause_evidence`
6. Classify as customer_symptom, agent_action, or system_message. → `root_cause_evidence_type`
7. List any contributing root cause codes. Return empty list if only one root cause. → `contributing_codes`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "root_cause_access_domain": "<string>",
    "root_cause_primary_code": "<RC_code>",
    "root_cause_primary_description": "<string>",
    "root_cause_justification": "<string>",
    "root_cause_evidence": "<string>",
    "root_cause_evidence_type": "<customer_symptom | agent_action | system_message>",
    "contributing_codes": ["<item1>", "<item2>"]
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, root_cause_access_domain, root_cause_primary_code, root_cause_primary_description, root_cause_justification, root_cause_evidence, root_cause_evidence_type, contributing_codes"""


def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_ROOT_CAUSE_EVIDENCE_TYPE = frozenset({'customer_symptom', 'agent_action', 'system_message'})
    _v = str(record.get("root_cause_evidence_type", "")).strip().lower()
    if _v not in _VALID_ROOT_CAUSE_EVIDENCE_TYPE:
        logger.warning(
            "uid=%s: invalid root_cause_evidence_type %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_ROOT_CAUSE_EVIDENCE_TYPE)
        )
        record["root_cause_evidence_type"] = ""
    else:
        record["root_cause_evidence_type"] = _v
    return record


async def classify_root_cause(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run root_cause classification on all batches."""
    tax = taxonomies.get("root_cause", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "RC")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("root_cause: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_root_cause(batches, taxonomies, cfg))
