def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_OVERALL_PERFORMANCE_RATING = frozenset({'excellent', 'needs_improvement', 'poor', 'satisfactory', 'good'})
    _v = str(record.get("overall_performance_rating", "")).strip().lower()
    if _v not in _VALID_OVERALL_PERFORMANCE_RATING:
        logger.warning(
            "uid=%s: invalid overall_performance_rating %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_OVERALL_PERFORMANCE_RATING)
        )
        record["overall_performance_rating"] = ""
    else:
        record["overall_performance_rating"] = _v
    _VALID_EMPATHY_DISPLAYED = frozenset({'strong', 'minimal', 'adequate', 'none'})
    _v = str(record.get("empathy_displayed", "")).strip().lower()
    if _v not in _VALID_EMPATHY_DISPLAYED:
        logger.warning(
            "uid=%s: invalid empathy_displayed %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_EMPATHY_DISPLAYED)
        )
        record["empathy_displayed"] = ""
    else:
        record["empathy_displayed"] = _v
    _VALID_RESOLUTION_OWNERSHIP = frozenset({'not_applicable', 'full_ownership', 'deflected', 'partial_ownership'})
    _v = str(record.get("resolution_ownership", "")).strip().lower()
    if _v not in _VALID_RESOLUTION_OWNERSHIP:
        logger.warning(
            "uid=%s: invalid resolution_ownership %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_RESOLUTION_OWNERSHIP)
        )
        record["resolution_ownership"] = ""
    else:
        record["resolution_ownership"] = _v
    _VALID_TECHNICAL_ACCURACY = frozenset({'accurate', 'mostly_accurate', 'inaccurate', 'partially_inaccurate'})
    _v = str(record.get("technical_accuracy", "")).strip().lower()
    if _v not in _VALID_TECHNICAL_ACCURACY:
        logger.warning(
            "uid=%s: invalid technical_accuracy %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_TECHNICAL_ACCURACY)
        )
        record["technical_accuracy"] = ""
    else:
        record["technical_accuracy"] = _v
    return record


async def classify_agent_performance(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run agent_performance classification on all batches."""
    tax = taxonomies.get("agent_performance", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "AP")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("agent_performance: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_agent_performance(batches, taxonomies, cfg))
