def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_TIME_CRITICALITY = frozenset({'high', 'low', 'medium', 'critical'})
    _v = str(record.get("time_criticality", "")).strip().lower()
    if _v not in _VALID_TIME_CRITICALITY:
        logger.warning(
            "uid=%s: invalid time_criticality %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_TIME_CRITICALITY)
        )
        record["time_criticality"] = ""
    else:
        record["time_criticality"] = _v
    _VALID_URGENCY = frozenset({'soon', 'emergency', 'urgent', 'routine'})
    _v = str(record.get("urgency", "")).strip().lower()
    if _v not in _VALID_URGENCY:
        logger.warning(
            "uid=%s: invalid urgency %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_URGENCY)
        )
        record["urgency"] = ""
    else:
        record["urgency"] = _v
    return record


async def classify_metadata(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run metadata classification on all batches."""
    system_prompt = _SYSTEM_PROMPT

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("metadata: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_metadata(batches, taxonomies, cfg))
