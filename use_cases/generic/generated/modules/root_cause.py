logger = logging.getLogger(__name__)

MODULE_NAME = "root_cause"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Identify the underlying root cause of the customer's issue. Distinguish between the symptom (what the customer reported) and the root cause (why it happened). Use the evidence field to cite specific transcript signals that support the classification.

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Select the single most specific L2 code that identifies WHY the issue occurred (not what the issue is - that is contact_reason). Consider what systemic or situational factor caused the problem. Use L1 only if no L2 fits. Return the exact code. → `root_cause_primary_code`
2. Explain in one sentence (max 30 words) what caused the issue and why you assigned this root cause code. Be specific - avoid generic phrases like 'technical issue occurred'. → `root_cause_primary_description`
3. Rate your confidence: confirmed - the transcript explicitly states what caused the issue (e.g. agent or customer describes the cause directly); probable - strong circumstantial evidence points to this cause; suspected - limited evidence, but this is the most plausible cause given context; unclear - insufficient information to determine root cause. → `root_cause_confidence`
4. Extract the transcript passage (verbatim or close paraphrase, max 50 words) that most directly reveals the root cause. If the root cause is inferred rather than stated, cite the evidence that led to your inference. → `root_cause_evidence`
5. List up to 2 additional root cause codes (e.g. ['RC3.2', 'RC6.1']) that contributed to the issue in addition to the primary root cause. Return [] if there are none. Do not repeat the primary code. → `root_cause_contributing_factors`
6. Return true if the transcript contains signals that this is a systemic or widespread issue: customer mentions others are affected, agent acknowledges a known issue, issue is attributed to a policy or process (not a one-off error). Return false if this appears to be an isolated incident. → `is_systemic_issue`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "root_cause_primary_code": "<RC_code>",
    "root_cause_primary_description": "<string>",
    "root_cause_confidence": "<confirmed | probable | suspected | unclear>",
    "root_cause_evidence": "<string>",
    "root_cause_contributing_factors": ["<item1>", "<item2>"],
    "is_systemic_issue": true
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, root_cause_primary_code, root_cause_primary_description, root_cause_confidence, root_cause_evidence, root_cause_contributing_factors, is_systemic_issue"""


def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_ROOT_CAUSE_CONFIDENCE = frozenset({'probable', 'confirmed', 'suspected', 'unclear'})
    _v = str(record.get("root_cause_confidence", "")).strip().lower()
    if _v not in _VALID_ROOT_CAUSE_CONFIDENCE:
        logger.warning(
            "uid=%s: invalid root_cause_confidence %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_ROOT_CAUSE_CONFIDENCE)
        )
        record["root_cause_confidence"] = ""
    else:
        record["root_cause_confidence"] = _v
    return record


async def classify_root_cause(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run root_cause classification on all batches."""
    tax = taxonomies.get("root_cause", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "RC")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("root_cause: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_root_cause(batches, taxonomies, cfg))
