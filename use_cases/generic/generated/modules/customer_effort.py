def _validate_record(record: dict) -> dict:
    """Validate enum fields and normalise casing."""
    _VALID_EFFORT_SCORE = frozenset({'low', 'high', 'very_low', 'medium', 'very_high'})
    _v = str(record.get("effort_score", "")).strip().lower()
    if _v not in _VALID_EFFORT_SCORE:
        logger.warning(
            "uid=%s: invalid effort_score %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_EFFORT_SCORE)
        )
        record["effort_score"] = ""
    else:
        record["effort_score"] = _v
    _VALID_RESOLUTION_TRANSPARENCY = frozenset({'opaque', 'partial', 'full', 'not_applicable'})
    _v = str(record.get("resolution_transparency", "")).strip().lower()
    if _v not in _VALID_RESOLUTION_TRANSPARENCY:
        logger.warning(
            "uid=%s: invalid resolution_transparency %r — setting to blank. Allowed: %s",
            record.get("uid","?"), _v, sorted(_VALID_RESOLUTION_TRANSPARENCY)
        )
        record["resolution_transparency"] = ""
    else:
        record["resolution_transparency"] = _v
    return record


async def classify_customer_effort(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run customer_effort classification on all batches."""
    tax = taxonomies.get("customer_effort", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "CE")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        parse_fn=_validate_record,
    )

    logger.info("customer_effort: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_customer_effort(batches, taxonomies, cfg))
