MODULE_NAME = "regid_taxonomy"


def _build_system_prompt(taxonomy_prompt: str) -> str:
    _BEFORE = """You are an expert classifier for Elsevier support tickets.
Your task: Classify this customer support ticket into exactly one category from the taxonomy below. Each category carries its definition and, where the original tagger recorded them, the synonyms and phrasings they used for it. Match on what the definition describes, not on surface keywords. Read the whole thread before deciding. The customer opens, the agent replies, and the request is often restated or corrected further down. Classify on what the CUSTOMER is asking for, not on what the agent did about it. An agent who fulfils a request by issuing credentials, sending a link or raising a ticket does not change what was asked. Exactly one code. If two seem to fit, pick the one the customer would name themselves. Never return an empty code. Every ticket gets one. If the thread does not say enough to classify - an agent-only note with no customer request, an auto-reply, a bare acknowledgement, an attachment with no text - that is not a reason to leave the field blank, it is the reason the catch-all category exists. Use it. The catch-all is Not enough info. Assign the single best-fitting LEAF code (e.g. RIDT1.1).

## Taxonomy
"""
    _AFTER = """

## Instructions
1. Assign the single leaf-level code (e.g. RIDT1.1) for the category that best matches this ticket. Read each Definition in full and match on what the ticket shows, not on surface keywords. Only use codes from the taxonomy. → `ridt_code`
2. In one or two sentences, explain why this category applies and why the closest alternative category does not. Refer to what the ticket actually shows. Do not use apostrophes or quotation marks in your answer. → `ridt_justification`
3. Copy verbatim the single sentence or phrase from the transcript that most strongly supports this choice. Do not paraphrase, infer, or add words that are not in the transcript. If no direct evidence exists, return an empty string. → `ridt_evidence`

## Output Format
Return a JSON array — one object per record:
[
  {
    "uid": "<record uid>",
    "ridt_code": "<RIDT_code>",
    "ridt_justification": "<string>",
    "ridt_evidence": "<string>"
  }
]

IMPORTANT: Return ONLY valid JSON. No markdown fences. Every input uid MUST appear in output.
CRITICAL: Always use LEAF-level codes (with a dot, e.g. CR4.1), NEVER L1 group codes (e.g. CR4)."""
    return _BEFORE + taxonomy_prompt + _AFTER


_USER_PROMPT_TEMPLATE = """Classify the following support transcripts.

{records_json}

Return a JSON array with one object per record.
Each object must have: uid, ridt_code, ridt_justification, ridt_evidence"""





async def classify_regid_taxonomy(
    batches: list[list[dict[str, str]]],
    taxonomies: dict[str, dict],
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """Run regid_taxonomy classification on all batches."""
    tax = taxonomies.get("regid_taxonomy", {})
    tax_prompt = taxonomy_to_rich_prompt(tax, "RIDT")
    system_prompt = _build_system_prompt(tax_prompt)

    results = await process_batches_async(
        batches,
        system_prompt,
        _USER_PROMPT_TEMPLATE,
        cfg,
        
    )

    logger.info("regid_taxonomy: classified %d records", len(results))
    return results


def run(batches, taxonomies, cfg):
    """Synchronous wrapper."""
    return asyncio.run(classify_regid_taxonomy(batches, taxonomies, cfg))
