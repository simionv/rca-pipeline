logger = logging.getLogger(__name__)

# Hardcoded fallback for the four original domains — used when
# pipeline_config.json has not been generated yet.
_BUILTIN_PREFIX_MAP = {
    "contact_reason": "CR",
    "root_cause":     "RC",
    "resolution":     "RS",
    "troubleshooting": "TS",
}


def _read_module_cfg(domain: str) -> dict:
    """Return the pipeline_config.json module entry for domain, or {}."""
    try:
        return load_pipeline_config().get("modules", {}).get(domain, {})
    except Exception as e:
        logger.warning("_read_module_cfg: could not read pipeline_config.json: %s", e)
    return {}


def _get_discovery_mode(domain: str) -> str:
    """Return 'full', 'extract_only', or '' for domains not configured for discovery."""
    mode = _read_module_cfg(domain).get("discovery_mode", "")
    return mode if mode in ("full", "extract_only") else ""


def _get_extract_prompt(domain: str) -> str:
    """
    Return the Pass 1 extraction system prompt for a domain.

    Priority:
      1. extract_prompt from pipeline_config.json (set via the Excel modules sheet)
      2. Built-in prompt from _EXTRACT_SYSTEM_PROMPTS
      3. Fallback to the troubleshooting prompt
    """
    prompt = _read_module_cfg(domain).get("extract_prompt", "")
    if prompt:
        return prompt
    return _EXTRACT_SYSTEM_PROMPTS.get(domain, _EXTRACT_SYSTEM_PROMPTS["troubleshooting"])


def _get_prefix(domain: str) -> str:
    """
    Return the taxonomy prefix for a discovery domain.

    Reads from pipeline_config.json (generated by build_pipeline.py) so any
    module added via pipeline_definition.xlsx automatically gets the correct
    prefix without editing this file.

    Falls back to the builtin map for the four original domains, and then to
    the first two uppercase letters of the domain name for anything else.
    """
    try:
        prefix = load_pipeline_config().get("modules", {}).get(domain, {}).get("taxonomy_prefix", "")
        if prefix:
            return prefix
    except Exception as e:
        logger.warning("_get_prefix: could not read pipeline_config.json: %s", e)

    # Fallback 1 — builtin map for original domains
    if domain in _BUILTIN_PREFIX_MAP:
        return _BUILTIN_PREFIX_MAP[domain]

    # Fallback 2 — derive from domain name (e.g. "customer_effort" → "CE")
    parts   = domain.split("_")
    derived = "".join(p[0].upper() for p in parts if p)[:2]
    logger.warning(
        "_get_prefix: '%s' not in pipeline_config.json — using derived prefix '%s'",
        domain, derived,
    )
    return derived


