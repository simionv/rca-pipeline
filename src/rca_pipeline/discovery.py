_EXTRACT_USER_TEMPLATE = """Identify the distinct ABSTRACT categories from these support transcripts.
Remember: merge similar items into one category. Do NOT list surface-level variations separately.

{records_json}

Return a JSON array with uid and extracted_items (list of item/count objects)."""


async def extract_actions(
    records: list[dict[str, str]],
    domain: str,
    cfg: RunConfig,
) -> list[dict[str, Any]]:
    """
    Pass 1 – extract abstract action categories from transcripts in parallel.

    Parameters
    ----------
    records  list of {uid, text} dicts
    domain   one of: contact_reason, root_cause, resolution, troubleshooting
    cfg      RunConfig
    """
    system_prompt = _get_extract_prompt(domain)

    temp_df   = pd.DataFrame(records)
    batches_df = make_batches(temp_df, cfg.batch_size, cfg.max_chars_per_batch, "text")
    batches   = [
        [{"uid": str(row["uid"]), "text": str(row.get("text", ""))}
         for _, row in b.iterrows()]
        for b in batches_df
    ]

    results = await process_batches_async(batches, system_prompt, _EXTRACT_USER_TEMPLATE, cfg)
    logger.info("Discovery Pass 1 (%s): extracted from %d records", domain, len(results))
    return results


# ===========================================================================
# Pre-dedup: fuzzy collapse before normalisation
# ===========================================================================

def _pre_dedup_items(counter: Counter, threshold: float = 0.75) -> Counter:
    """
    Collapse near-duplicate items via token-overlap similarity.
    Higher-frequency items absorb lower-frequency near-duplicates.
    Reduces the item list the normalisation LLM sees, preventing it
    from preserving distinctions that are just wording variations.
    """
    items  = sorted(counter.items(), key=lambda x: -x[1])
    merged: Counter = Counter()

    def _tokenise(s: str) -> set[str]:
        return set(re.sub(r"[^a-z0-9\s]", "", s.lower()).split())

    for item, freq in items:
        tokens = _tokenise(item)
        if not tokens:
            continue
        matched = False
        for canonical in list(merged.keys()):
            c_tokens = _tokenise(canonical)
            if not c_tokens:
                continue
            similarity = len(tokens & c_tokens) / max(len(tokens), len(c_tokens))
            if similarity >= threshold:
                merged[canonical] += freq
                matched = True
                break
        if not matched:
            merged[item] = freq

    n_before, n_after = len(counter), len(merged)
    if n_before != n_after:
        logger.info("Pre-dedup: %d → %d items (%d merged)", n_before, n_after, n_before - n_after)
    return merged


