"""
discovery.py – Taxonomy Discovery Module
==========================================
Extracts a structured taxonomy from raw transcripts when no taxonomy exists.

Two-pass process
----------------
Pass 1  extract_actions()   – Parallel LLM batches extract abstract category
                               phrases from each transcript.  A pre-dedup step
                               collapses near-duplicates (token-overlap >= 0.75)
                               before sending to Pass 2.

Pass 2  normalise()         – Single LLM call on the top-N frequency items.
                               Produces a structured JSON taxonomy with exactly
                               2 levels of dot-notation codes.

Pass 3  save_discovered_taxonomy()  – Write to disk for human review.

Supported domains
-----------------
  Any module defined in pipeline_definition.xlsx.  The taxonomy prefix (e.g.
  CR, RC, CE) is read from pipeline_config.json at runtime so new modules
  added via the Excel are automatically discovered with the correct prefix.
  Falls back to the builtin map for the four original domains when
  pipeline_config.json is not present.

Bug fixes vs original
---------------------
- normalise() now uses _get_prefix() which reads the prefix from
  pipeline_config.json instead of a hardcoded dict, so any module added
  via pipeline_definition.xlsx gets the correct prefix automatically.
- normalise() now uses the resilient _llm_call() from llm_client instead of a
  bare litellm.acompletion() call.  Any transient API error is retried with
  the same exponential-backoff policy as every other LLM call.
- run_all_discoveries() now runs all domains concurrently with asyncio.gather()
  instead of a sequential for loop.
- pandas and litellm imported at module level.
"""

