_NORMALISE_SYSTEM_PROMPT = """You are a taxonomy engineer designing a CONCISE, NON-OVERLAPPING classification
taxonomy from observed data.

## CODE FORMAT — Numbered dot notation:
  L1 categories : {prefix}1, {prefix}2, {prefix}3, ...
  Leaf items    : {prefix}1.1, {prefix}1.2, {prefix}2.1, {prefix}2.2, ...

  Example:
    CR1   = "Account Issues"
    CR1.1 = "Login / Authentication Issue"
    CR1.2 = "Account Deletion Request"
    CR2   = "Technical Problems"
    CR2.1 = "Application Error"

## HARD CONSTRAINTS:
1. EXACTLY 2 levels — L1 ({prefix}N) and leaf ({prefix}N.M).  Never {prefix}N.M.X.
2. TARGET: 4–8 L1 categories, 2–6 leaves per L1, 15–40 total leaf codes.
3. ZERO OVERLAP — every real-world case fits exactly ONE leaf code.
4. ABSTRACT LABELS — generic operational language, not transcript wording.
5. Include one "Other / General" leaf under each L1 for edge cases.
6. Every node (L1 and leaf) MUST include a "description" field — 1–2 sentences
   explaining what belongs in that category and how to distinguish it from
   adjacent categories.  This is used directly in classification prompts, so
   make it precise and actionable.

Return ONLY a JSON object.  No markdown fences.  No commentary.
Structure:
{{
  "{prefix}1": {{
    "label": "Category Name",
    "description": "1-2 sentence explanation of what this L1 category covers.",
    "children": {{
      "{prefix}1.1": {{
        "label": "Leaf Label",
        "description": "Precise definition of this leaf. What distinguishes it from {prefix}1.2?"
      }},
      "{prefix}1.2": {{
        "label": "Another Leaf",
        "description": "Precise definition of this leaf. What distinguishes it from {prefix}1.1?"
      }},
      "{prefix}1.3": {{
        "label": "Other Category-Related Issues",
        "description": "Cases that fall within this L1 category but do not fit any specific leaf above."
      }}
    }}
  }},
  "{prefix}2": {{
    "label": "Second Category",
    "description": "1-2 sentence explanation of what this L1 category covers.",
    "children": {{
      "{prefix}2.1": {{
        "label": "Leaf Label",
        "description": "Precise definition of this leaf."
      }},
      "{prefix}2.2": {{
        "label": "Other Second-Category Issues",
        "description": "Cases that fall within this L1 category but do not fit any specific leaf above."
      }}
    }}
  }}
}}"""


def _build_normalise_prompt(
    items_with_freq: list[tuple[str, int]], prefix: str, top_n: int
) -> str:
    sorted_items = sorted(items_with_freq, key=lambda x: x[1], reverse=True)[:top_n]
    items_text   = "\n".join(f"  - {item} (freq: {freq})" for item, freq in sorted_items)
    return f"""Here are the extracted items ranked by frequency:

{items_text}

Create a taxonomy with prefix "{prefix}" using NUMBERED DOT NOTATION.
Codes: {prefix}1, {prefix}2, ... for L1 and {prefix}1.1, {prefix}1.2, ... for leaves.

REMEMBER:
- EXACTLY 2 levels: {prefix}N → {prefix}N.M (never deeper)
- 4–8 L1 categories, 2–6 leaves each
- AGGRESSIVELY merge similar items — fewer non-overlapping codes is better
- Include an "Other" leaf per L1 for edge cases
- Every node MUST have both "label" AND "description" fields
- Return the JSON WITHOUT any top-level wrapper key — start directly with {prefix}1

Return the taxonomy as a JSON object."""


async def normalise(
    extraction_results: list[dict[str, Any]],
    domain: str,
    cfg: RunConfig,
    output_dir: str | Path | None = None,
) -> dict:
    """
    Pass 2 – normalise extracted items into a structured taxonomy.
    Single LLM call on aggregated + pre-deduplicated items.

    Parameters
    ----------
    extraction_results : list of Pass 1 result dicts (each has extracted_items)
    domain             : taxonomy domain name
    cfg                : RunConfig
    output_dir         : if set, always saves the Pass 1 extraction counter here
                         as <domain>_extracted.json — useful for diagnosing why
                         normalise produced an empty taxonomy.
    """
    prefix = _get_prefix(domain)

    # Aggregate extracted items with frequencies
    counter: Counter = Counter()
    for result in extraction_results:
        items = result.get("extracted_items", [])
        if not isinstance(items, list):
            logger.debug(
                "normalise: uid=%s has non-list extracted_items (%s) — skipping",
                result.get("uid", "?"), type(items).__name__,
            )
            continue
        for item in items:
            if isinstance(item, dict):
                name  = item.get("item", item.get("action", ""))
                count = item.get("count", 1)
                if name:
                    counter[name.strip().lower()] += count

    # Always save the Pass 1 counter when output_dir is provided so callers
    # can diagnose failures even when normalise returns {}.
    if output_dir and counter:
        try:
            save_extraction_results(counter, domain, output_dir)
        except Exception as _e:
            logger.debug("normalise: could not save extraction results: %s", _e)

    if not counter:
        logger.warning(
            "normalise: no items extracted for domain '%s' — "
            "Pass 1 returned %d result(s) but none had non-empty 'extracted_items'. "
            "Check that the LLM is returning the expected JSON schema: "
            "[{\"uid\": \"...\", \"extracted_items\": [{\"item\": \"...\", \"count\": 1}]}]",
            domain, len(extraction_results),
        )
        return {}

    counter = _pre_dedup_items(counter)

    system_prompt = _NORMALISE_SYSTEM_PROMPT.format(prefix=prefix)
    user_prompt   = _build_normalise_prompt(list(counter.items()), prefix, cfg.discovery_top_n)

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user",   "content": user_prompt},
    ]

    # Resilient call — retried by the same exponential-backoff policy as all
    # other LLM calls (cfg.retries attempts, not a bare single shot).
    try:
        raw      = await _llm_call(messages, cfg)
        taxonomy = robust_json_loads(raw)
    except Exception as e:
        logger.error("normalise: LLM call failed for domain '%s': %s", domain, e)
        return {}

    if not isinstance(taxonomy, dict):
        # LLM sometimes wraps the taxonomy in a list: [{...}]
        # Try to unwrap a single-element list whose sole item is a dict.
        if isinstance(taxonomy, list) and len(taxonomy) == 1 and isinstance(taxonomy[0], dict):
            taxonomy = taxonomy[0]
            logger.info("normalise: unwrapped list-wrapped taxonomy for domain '%s'", domain)
        else:
            logger.warning(
                "normalise: non-dict response for domain '%s' (type=%s) — "
                "raw (first 300 chars): %s",
                domain, type(taxonomy).__name__, repr(raw[:300]),
            )
            return {}

    taxonomy = _enforce_max_depth(taxonomy, prefix)
    logger.info("Discovery Pass 2 (%s): taxonomy normalised", domain)
    return taxonomy


# ===========================================================================
# Post-validation: enforce max depth
# ===========================================================================

def _enforce_max_depth(taxonomy: dict, prefix: str) -> dict:
    """
    Ensure exactly 2 levels of dot notation: PREFIX_N → PREFIX_N.M.
    Strips any wrapper key, truncates over-deep codes, flattens sub-children.

    Also handles LLMs that emit leaf codes at the top level (outside children):
      {'CR1': {'label': '...'}, 'CR1.1': {'label': '...'}, 'CR1.2': {'label': '...'}}
    These orphaned leaves are reassigned to their parent L1 node's children dict.
    """
    # Unwrap single-key wrapper that isn't itself a labelled node
    if prefix in taxonomy and isinstance(taxonomy[prefix], dict):
        taxonomy = taxonomy[prefix]
    if len(taxonomy) == 1:
        only = list(taxonomy.values())[0]
        if isinstance(only, dict) and "label" not in only:
            taxonomy = only

    # ── Separate L1 nodes from orphaned top-level leaf codes ──────────────
    l1_nodes:      dict[str, dict] = {}
    orphan_leaves: dict[str, dict] = {}

    for code, node in taxonomy.items():
        if not isinstance(node, dict):
            continue
        if "." in code:
            orphan_leaves[code] = node   # e.g. CR1.1 at top level
        else:
            l1_nodes[code] = node        # e.g. CR1

    if orphan_leaves:
        logger.info(
            "_enforce_max_depth: found %d top-level leaf codes — reassigning to parent L1s",
            len(orphan_leaves),
        )

    cleaned: dict = {}

    for l1_code, l1_node in l1_nodes.items():
        cleaned_children: dict = {}

        # First, add any orphaned leaves that belong to this L1
        for leaf_code, leaf_node in orphan_leaves.items():
            parts = leaf_code.split(".")
            if parts[0] == l1_code:
                flat_code = f"{parts[0]}.{parts[1]}"
                if flat_code not in cleaned_children:
                    entry = {"label": leaf_node.get("label", flat_code)}
                    if leaf_node.get("description"):
                        entry["description"] = leaf_node["description"]
                    cleaned_children[flat_code] = entry

        # Then process children declared inside the L1 node
        for leaf_code, leaf_node in l1_node.get("children", {}).items():
            if not isinstance(leaf_node, dict):
                continue

            dot_count = leaf_code.count(".")
            if dot_count > 1:
                parts     = leaf_code.split(".")
                leaf_code = f"{parts[0]}.{parts[1]}"
                if leaf_code not in cleaned_children:
                    entry = {"label": leaf_node.get("label", "")}
                    if leaf_node.get("description"):
                        entry["description"] = leaf_node["description"]
                    cleaned_children[leaf_code] = entry
            elif dot_count == 0:
                # No dot — mis-structured; include anyway
                entry = {"label": leaf_node.get("label", leaf_code)}
                if leaf_node.get("description"):
                    entry["description"] = leaf_node["description"]
                cleaned_children[leaf_code] = entry
            else:
                entry = {"label": leaf_node.get("label", leaf_code)}
                if leaf_node.get("description"):
                    entry["description"] = leaf_node["description"]
                cleaned_children[leaf_code] = entry

            # Flatten any deeper sub-children
            if "children" in leaf_node:
                for sub_code, sub_node in leaf_node["children"].items():
                    sub_parts = sub_code.split(".")
                    flat_code = f"{sub_parts[0]}.{sub_parts[1]}" if len(sub_parts) > 2 else sub_code
                    if flat_code not in cleaned_children:
                        sub_entry = {
                            "label": sub_node.get("label", "") if isinstance(sub_node, dict) else str(sub_node)
                        }
                        if isinstance(sub_node, dict) and sub_node.get("description"):
                            sub_entry["description"] = sub_node["description"]
                        cleaned_children[flat_code] = sub_entry
                cleaned_children.get(leaf_code, {}).pop("children", None)

        l1_entry = {
            "label":    l1_node.get("label", l1_code),
            "children": cleaned_children,
        }
        if l1_node.get("description"):
            l1_entry["description"] = l1_node["description"]
        cleaned[l1_code] = l1_entry

    return cleaned


# ===========================================================================
# Pass 3 – save discovered taxonomy for human review
# ===========================================================================

def save_discovered_taxonomy(
    taxonomy: dict,
    domain: str,
    output_dir: str | Path,
    filename: str | None = None,
) -> Path:
    """
    Save a discovered taxonomy to a JSON file.
    Uses a _discovered suffix to distinguish from curated production taxonomies.
    Human editorial review is expected before promoting to production.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    filename   = filename or f"{domain}_discovered.json"
    filepath   = output_dir / filename

    with open(filepath, "w", encoding="utf-8") as fh:
        json.dump(taxonomy, fh, indent=2, ensure_ascii=False)

    logger.info("Saved discovered taxonomy: %s", filepath)
    return filepath


def save_extraction_results(
    counter: Counter,
    domain: str,
    output_dir: str | Path,
) -> Path:
    """
    Save frequency-ranked extraction items for extract_only domains.
    No taxonomy is built — the ranked list is the artefact for human review.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    filepath = output_dir / f"{domain}_extracted.json"
    items = [
        {"item": item, "frequency": freq}
        for item, freq in sorted(counter.items(), key=lambda x: -x[1])
    ]
    with open(filepath, "w", encoding="utf-8") as fh:
        json.dump({"domain": domain, "mode": "extract_only", "items": items}, fh,
                  indent=2, ensure_ascii=False)
    logger.info("Saved extraction results: %s", filepath)
    return filepath


# ===========================================================================
# Full discovery pipeline — single domain
# ===========================================================================

async def run_discovery(
    records: list[dict[str, str]],
    domain: str,
    cfg: RunConfig,
    output_dir: str | Path | None = None,
    mode: str | None = None,
) -> dict:
    """
    Discovery pipeline for one domain.

    mode='full'         — Pass 1 (extract) + Pass 2 (normalise → taxonomy JSON)
    mode='extract_only' — Pass 1 only; saves a frequency-ranked item list, no taxonomy
    mode=None           — read from pipeline_config.json; defaults to 'full' if not set

    Returns the discovered taxonomy dict ('full') or {} ('extract_only').
    """
    if mode is None:
        mode = _get_discovery_mode(domain) or "full"

    extraction_results = await extract_actions(records, domain, cfg)

    if mode == "extract_only":
        if output_dir:
            counter: Counter = Counter()
            for result in extraction_results:
                for item in result.get("extracted_items", []):
                    if isinstance(item, dict):
                        name  = item.get("item", item.get("action", ""))
                        count = item.get("count", 1)
                        if name:
                            counter[name.strip().lower()] += count
            counter = _pre_dedup_items(counter)
            save_extraction_results(counter, domain, output_dir)
        logger.info("Discovery extract_only (%s): done — skipping normalise", domain)
        return {}

    taxonomy = await normalise(extraction_results, domain, cfg, output_dir=output_dir)
    if output_dir:
        save_discovered_taxonomy(taxonomy, domain, output_dir)
    return taxonomy


# ===========================================================================
# Full discovery pipeline — multiple domains (concurrent)
# ===========================================================================

async def run_all_discoveries(
    records: list[dict[str, str]],
    domains: list[str],
    cfg: RunConfig,
    output_dir: str | Path | None = None,
) -> dict[str, dict]:
    """
    Run discovery for multiple domains concurrently.

    Bug fix: domains are now run with asyncio.gather() instead of a sequential
    for loop — wall-time for 4 domains is roughly quartered.

    Returns {domain: taxonomy_dict}
    """
    async def _one(domain: str) -> tuple[str, dict]:
        mode = _get_discovery_mode(domain) or "full"
        logger.info("Starting discovery: %s (mode=%s)", domain, mode)
        taxonomy = await run_discovery(records, domain, cfg, output_dir, mode=mode)
        return domain, taxonomy

    pairs = await asyncio.gather(*[_one(d) for d in domains], return_exceptions=True)

    results: dict[str, dict] = {}
    for item in pairs:
        if isinstance(item, Exception):
            logger.error("Discovery domain failed: %s", item)
        else:
            domain, taxonomy = item
            results[domain] = taxonomy

    return results
