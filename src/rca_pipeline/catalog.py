"""
catalog.py – build CATALOG.md from the use-case pages
=====================================================
    rca catalog [--repo DIR]

Reads the block at the top of every use_cases/<name>/README.md and writes
CATALOG.md at the repository root: one row per use case, plus an index by tag.
Run it after adding or updating a use case.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

FIELDS = ("name", "title", "product", "status", "owner", "period", "updated", "tags", "question")


def read_front_matter(readme: Path) -> dict[str, object]:
    text = readme.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    meta: dict[str, object] = {}
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = re.sub(r"\s+#.*$", "", value).strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [t.strip() for t in value[1:-1].split(",") if t.strip()]
        else:
            meta[key.strip()] = value
    return meta


def build_catalog(repo: Path) -> str:
    entries = []
    for readme in sorted((repo / "use_cases").glob("*/README.md")):
        if readme.parent.name.startswith("_"):
            continue
        meta = read_front_matter(readme)
        meta["folder"] = readme.parent.name
        entries.append(meta)

    order = {"active": 0, "complete": 1, "superseded": 2}
    entries.sort(key=lambda e: (order.get(str(e.get("status", "")), 3), str(e.get("product", "")), e["folder"]))

    lines = [
        "# Use-case catalog",
        "",
        "Every analysis done with this pipeline, one row each. Click a name for its page "
        "(question, data, approach, results, lessons, how to re-run).",
        "To add one: copy `use_cases/_template`, fill in its README, then run `rca catalog`.",
        "",
        "| use case | product | question | tags | status | period |",
        "|---|---|---|---|---|---|",
    ]
    for e in entries:
        tags = ", ".join(e.get("tags") or [])
        title = e.get("title") or e["folder"]
        lines.append(f"| [{title}](use_cases/{e['folder']}/README.md) | {e.get('product', '')} | "
                     f"{e.get('question', '')} | {tags} | {e.get('status', '')} | {e.get('period', '')} |")

    by_tag: dict[str, list[str]] = {}
    for e in entries:
        for t in e.get("tags") or []:
            by_tag.setdefault(t, []).append(f"[{e['folder']}](use_cases/{e['folder']}/README.md)")
    lines += ["", "## By technique", ""]
    for tag in sorted(by_tag):
        lines.append(f"- **{tag}**: {', '.join(by_tag[tag])}")
    lines += ["", "_Generated by `rca catalog` — edit the use-case READMEs, not this file._", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="rca catalog", description="Rebuild CATALOG.md from use-case pages.")
    p.add_argument("--repo", default=None, help="Repository root (default: search upwards for use_cases/)")
    args = p.parse_args(argv)
    repo = Path(args.repo) if args.repo else next(
        (d for d in [Path.cwd(), *Path.cwd().parents] if (d / "use_cases").is_dir()), None)
    if repo is None:
        p.error("could not find a use_cases/ folder; pass --repo")
    out = repo / "CATALOG.md"
    out.write_text(build_catalog(repo), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
